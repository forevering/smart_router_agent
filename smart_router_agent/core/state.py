"""
Graph State 定义
使用 TypedDict + Annotated 管理 LangGraph 的全局状态结构。
messages 字段通过 operator.add 实现跨节点/跨轮次的消息累积（由 Checkpoint 自动持久化为 STM）。
"""
import operator
from typing import TypedDict, Annotated, List, Dict, Any


class AgentState(TypedDict):
    # =====================================================================
    # Short Term Memory (STM)
    # 通过 LangGraph Checkpoint 自动管理，同一 thread_id 下跨轮次累积。
    # operator.add 确保每个节点返回的新消息会追加到已有消息列表中。
    # =====================================================================
    messages: Annotated[list, operator.add]

    # =====================================================================
    # 用户标识 —— 用于索引 LTM 和 KG 的外部持久化存储
    # =====================================================================
    user_id: str

    # =====================================================================
    # Long Term Memory (LTM) —— 从 MemoryStore 检索的事实列表
    # 每轮由 retrieve_ltm 节点刷新，非累积式（覆盖写）
    # =====================================================================
    long_term_memory: List[str]

    # =====================================================================
    # Knowledge Graph Context —— 从 TemporalKG 检索的当前有效信息
    # 每轮由 retrieve_kg 节点刷新，非累积式（覆盖写）
    # =====================================================================
    kg_context: List[str]

    # =====================================================================
    # Query Rewriter 输出 —— 融合 LTM/KG/STM 后的改写查询
    # 供 tool_retriever 使用，提升工具检索准确度
    # =====================================================================
    contextualized_query: str

    # =====================================================================
    # Generator 生成的最终回复文本
    # =====================================================================
    response: str
